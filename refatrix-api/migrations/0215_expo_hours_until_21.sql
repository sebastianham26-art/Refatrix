-- 0215 · 전시회 미팅 시간표를 저녁 9시(21:00)까지 — 디렉터 요청 2026-09-10
--
--   RUJAC 시간표가 08:00~18:00 (10칸)이라 저녁 미팅을 걸 칸이 없었다.
--   → 기본 종료 시각을 21 로 올리고, 지금 18시로 등록돼 있는 전시회를 21시로 늘린다.
--      (08:00~21:00 = 13칸, 마지막 칸은 20:00–21:00)
--
--   · 이미 걸려 있는 미팅은 칸(day_no × slot_hour)이 그대로라 영향 없음 — 칸이 늘기만 한다.
--   · 18시가 아닌 값(디렉터가 ⚙ 설정에서 직접 고른 19·20·22시 등)은 건드리지 않는다.
--   · 나중에 다시 줄이거나 늘리려면 ⚙ 전시회 설정 → 종료 시각에서 바꾸면 된다(마이그레이션 불필요).
--   · 멱등: 두 번 돌아도 18시 행이 없으면 아무 일도 없다.

ALTER TABLE exhibitions ALTER COLUMN end_hour SET DEFAULT 21;

UPDATE exhibitions
   SET end_hour = 21, updated_at = now()
 WHERE deleted_at IS NULL
   AND end_hour = 18;
