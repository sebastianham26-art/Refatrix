-- 0225 · 고객 PO번호(Orden de compra del cliente) — 우리 오더번호와 **나란히** 다닌다
--
--   왜 필요했나 (디렉터 지시, 2026-09-18)
--     고객은 자기 PO번호로 주문을 관리한다. 우리는 견적번호(Q-2026-#### / COT-…)로 관리한다.
--     그래서 창고가 패킹리스트를 들고 나가면 고객 창고에서 **대조가 안 된다** —
--     「Pedido: Q-2026-0431」 이라고 적힌 종이를 받아도 고객 시스템에는 그런 번호가 없다.
--     전화로 「우리 PO 4471번 언제 와요?」 라고 물으면 ERP 에서 찾을 방법이 아예 없었다.
--
--   그래서 번호를 **버리지 않고 같이 들고 다닌다.**
--     · 견적(=오더) 1건에 고객 PO 1개. 견적에 달아 두면 포장·매출·수금까지 자동으로 따라간다.
--       (인보이스에 따로 칼럼을 두지 않는다 — 인보이스는 견적을 통해 PO 에 닿는다.
--        두 군데 두면 언젠가 갈리고, 갈린 날 어느 쪽이 맞는지 아무도 모른다)
--     · 웹(CRM)에서 `ordenCompraCliente` 로 들어와도 같은 칸에 들어간다.
--       화면 입력과 수신 창구가 **같은 칸**을 써야 검색이 한 번에 끝난다.
--
--   ⚠ UNIQUE 를 걸지 않는다. 고객이 같은 PO번호로 분할 발주하는 일이 흔하고,
--     서로 다른 고객이 우연히 같은 번호를 쓰는 일은 더 흔하다(1, 001, 2026-1 …).
--     번호는 **찾기 위한 것**이지 잠그기 위한 것이 아니다.

ALTER TABLE quotes ADD COLUMN IF NOT EXISTS customer_po_no TEXT;   -- 고객이 발행한 PO(O.C.) 번호 원문

-- 검색용. 화면 3곳(견적 목록·매출 확정 목록·창고)에서 대소문자 무시 부분일치로 찾는다.
--   원문은 그대로 보존하고(인쇄에 그대로 나간다) 인덱스만 lower() 로 둔다.
CREATE INDEX IF NOT EXISTS idx_quotes_customer_po
  ON quotes (lower(customer_po_no))
  WHERE customer_po_no IS NOT NULL AND customer_po_no <> '';
